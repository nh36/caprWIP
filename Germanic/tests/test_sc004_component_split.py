class ProductionCascadeTests(unittest.TestCase):
    """The production germanic.txt places the two components at their genuine
    stages and preserves the frozen corpus outputs."""

    def setUp(self):
        self.src = FST_SOURCE.read_text(encoding="utf-8")

    def test_frozen_outputs_preserved(self):
        summary = json.loads(SUMMARY_JSON.read_text(encoding="utf-8"))
        self.assertEqual(summary["outputs_sha256"], FROZEN_OUTPUTS_SHA,
                         "combined production cascade must preserve every lexical output")
        self.assertEqual(summary["matched"], 372)
        self.assertEqual(summary["mismatched"], 8)

    def test_sc014_leads_early_english_line_changes(self):
        m = re.search(r"define EarlyEnglishLineChanges \[\s*\n\s*([A-Za-z0-9]+)", self.src)
        self.assertIsNotNone(m, "cannot locate EarlyEnglishLineChanges head")
        self.assertEqual(m.group(1), "PNWGmcUnstressedAiMonophthongization",
                         "SC014 must lead EarlyEnglishLineChanges (its old SC004 slot)")

    def test_sc004_general_runs_in_eaf_corridor_after_sc028(self):
        # EAFAiMonophthongization is composed immediately after
        # PNWGmcPreconsonantalXLoss (SC028) in both pipeline branches.
        pat = re.compile(
            r"\.o\. PNWGmcPreconsonantalXLoss\b.*\n(?:\s*#.*\n)*\s*\.o\. EAFAiMonophthongization\b")
        self.assertGreaterEqual(len(pat.findall(self.src)), 2,
                                "SC004 general must follow SC028 in both branches")

    def test_alias_is_not_composed_in_any_pipeline(self):
        # PWGmcAiMonophthongization survives only as a standalone define; it must
        # never be composed with `.o.` into a pipeline.
        self.assertNotIn(".o. PWGmcAiMonophthongization", self.src)
        self.assertNotRegex(self.src, r"PWGmcAiMonophthongization\s+\.o\.")
        self.assertIn("define PWGmcAiMonophthongization", self.src)

    def test_obsolete_breve_ai_no_op_is_gone(self):
        # The old SC014 no-op rewrite {*ăi} -> {*ē} must no longer exist as an
        # active rule. A historical mention in a comment line is allowed.
        active = [ln for ln in self.src.splitlines()
                  if "{*ăi}" in ln and not ln.lstrip().startswith("#")]
        self.assertEqual(active, [],
                         "the breve-marked {*ăi} no-op must not survive as an active rule")


if __name__ == "__main__":
    unittest.main()
