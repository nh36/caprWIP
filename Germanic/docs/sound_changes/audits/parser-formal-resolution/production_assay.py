#!/usr/bin/env python3
"""Replay the preserved four-cell assay with the authorized canonical parser."""
import argparse
import gzip
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

import alignment
import canonical_experiment
import experiment
import functionality


PARSER = """define PGCellRaw [PGCellPlain | PGCellPrefixed];
# Ambiguous bare spellings require explicit primary stress, not parse priority.
define PGCellCanonical _unambpart(PGCellRaw);
# Separate lexical tokenisation from morphological acceptance. The productive
# relation only inserts stars: its inverse is star erasure on its lower domain.
define PGCellStrip [
    {*}:0 | pgrmInitSimple.u | pgrmShortVowel.u |
    pgrmLongVowel.u | pgrmNasalVowel.u
]*;
define PGCellInput [PGCellStrip.i .o. PGCellCanonical.l];"""
INPUT = """# Compile this equivalent canonical union directly: recomposition through
# PGCellInput re-exposes the pinned checker's delayed-alignment defect.
define EnglishProtoInput [
    _unambpart(EnglishProtoNative) |
    _unambpart([[PGCellRaw.u - EnglishProtoNative.u] .o. PGCellRaw])
];"""


def canonical_source(source):
    for name, replacement in (("PGCellInput", PARSER), ("EnglishProtoInput", INPUT)):
        source, count = re.subn(r"(?ms)^define " + name + r"\b.*?;", replacement, source)
        if count != 1:
            raise ValueError("Expected exactly one candidate definition: " + name)
    return source


def certify_parser(fst, output):
    from anglo_frisian_experiments import compile_isolated, prepare_definition_image

    reference = experiment.ROOT / (
        ".capr-work/experiments/parser-canonical-alignment-02/results/PGCanonBuiltin.att")
    report, sources = {}, {}
    with tempfile.TemporaryDirectory(prefix="capr_actual_parser_gate_") as temporary:
        directory = Path(temporary)
        image = prepare_definition_image(fst, directory)
        if image:
            os.environ["CAPR_FOMA_DEFINITION_IMAGE"] = str(image)
        names = ("EnglishProtoInput", "PGCellInput")
        recipe = dict(
            definitions="", insert_after="", insert_rule="", replace={},
            component_checks=[dict(component=name) for name in names])
        bins = compile_isolated(fst, recipe, [], directory, components_only=True)
        for name in names:
            path = output / (name + ".att")
            commands = ["load stack " + str(bins["component:" + name]), "test functional",
                        "test unambiguous", "write att > " + str(path), "quit"]
            argv = ["foma", "-q"]
            for command in commands:
                argv.extend(["-e", command])
            result = subprocess.run(argv, capture_output=True, text=True, check=True, timeout=180)
            sources[name] = path.read_text()
            proof = functionality.analyze(sources[name])
            if proof["functional"]:
                functionality.verify(sources[name], proof)
            (output / (name + "-proof.json")).write_text(json.dumps(proof))
            report[name] = dict(stdout=result.stdout, independent=proof["functional"])
        union = canonical_experiment.relation_union(reference.read_text(), sources["EnglishProtoInput"])
        proof = functionality.analyze(union)
        if proof["functional"]:
            functionality.verify(union, proof)
        (output / "canonical-equivalence-union.att").write_text(union)
        (output / "canonical-equivalence-proof.json").write_text(json.dumps(proof))
        report["same_outputs"] = proof["functional"]
        report["same_domain"] = alignment.domain_check(
            [reference.read_text(), sources["EnglishProtoInput"]], lambda f: f[0] == f[1])
    (output / "parser-gate.json").write_text(json.dumps(report, indent=2))
    if (not report["same_outputs"] or not report["same_domain"]["valid"]
            or any(not report[n]["independent"] or
                   not report[n]["stdout"].startswith("1 ") for n in names)):
        raise RuntimeError("The exact composed parser did not satisfy the formal gate")


def worker(output):
    import adoption_assay

    output.mkdir()
    fst = adoption_assay.G / "fsts/germanic.txt"
    fst.write_text(canonical_source(fst.read_text()))
    shutil.copyfile(fst, output / "candidatefst.txt")
    shutil.copyfile(adoption_assay.G / "data/germanic-aligned-final.tsv",
                    output / "candidatecorpus.tsv")
    certify_parser(fst, output)
    historical = json.loads(gzip.decompress(
        (adoption_assay.RESEARCH / "results.json.gz").read_bytes()))
    missing = {p for p in historical["protected_before"] if not Path(p).is_file()}
    if any("/__pycache__/" not in p or not p.endswith(".pyc") for p in missing):
        raise RuntimeError("Missing canonical protected file other than generated bytecode")
    original_sha = adoption_assay.research.resolution.sha

    def qualified_sha(path):
        if str(path) in missing and not Path(path).exists():
            return None
        return original_sha(path)

    before = {p: qualified_sha(Path(p)) for p in historical["protected_before"]}
    adoption_assay.research.resolution.sha = qualified_sha
    try:
        adoption_assay.worker(output / "integration-results.json.gz")
    finally:
        after = {p: qualified_sha(Path(p)) for p in historical["protected_before"]}
        (output / "canonical-protection.json").write_text(json.dumps(dict(
            before=before, after=after, unchanged=before == after,
            unavailable_historical_generated_bytecode=sorted(missing)), indent=2))
        adoption_assay.research.resolution.sha = original_sha
    if before != after:
        raise RuntimeError("Canonical protection changed")
    report = json.loads(gzip.decompress((output / "integration-results.json.gz").read_bytes()))
    if not report["formal"]["EnglishProtoInput"]["stdout"].startswith("1 "):
        raise RuntimeError("The actual complete input parser did not pass the native gate")
    print(json.dumps(dict(
        canonical_unchanged=report["canonical_unchanged"],
        frozen_K_equal=report["frozen_K_equal"], formal=report["formal"],
        selected=report["candidate_baseline"]["summary"]), ensure_ascii=False))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--id")
    parser.add_argument("--worker", type=Path)
    args = parser.parse_args()
    if args.worker:
        worker(args.worker)
    else:
        experiment.host(args.id, entry=Path(__file__), extra_files=[
            Path(m.__file__) for m in (experiment, alignment, canonical_experiment)
        ] + [experiment.ROOT / (
            ".capr-work/experiments/parser-canonical-alignment-02/results/PGCanonBuiltin.att")])
